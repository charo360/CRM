    "gmail.com", "yahoo.com", "outlook.com", "hotmail.com", "icloud.com",
    "protonmail.com", "live.com", "aol.com", "me.com", "mail.com",
    "zoho.com", "yandex.com", "gmx.com", "web.de", "msn.com", "comcast.net",
